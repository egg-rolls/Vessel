import { resolve } from 'node:path';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

/**
 * Usage plugin UI build (CONTRACT-0.45).
 *
 * Sources live in `web-src/`; the published iframe payload is `web/`. The
 * manifest keeps `ui.dir: web` and the three page entries unchanged, so the
 * host and its `/plugins/<id>/<entry>` static route need no changes.
 *
 * `base: './'` keeps the assets relative to the HTML file: an opaque-origin
 * sandboxed iframe has no useful origin to build absolute URLs from.
 */
const root = resolve(__dirname, 'web-src');
const pluginUiSrc = resolve(__dirname, '../../../packages/plugin-ui/src');

/**
 * Generated chunks are committed, so they must not trip biome's format/lint
 * gate. Both files are machine output; the suppression is part of the bundle.
 */
function generatedBiomeIgnore(): Plugin {
  return {
    name: 'vessel-generated-biome-ignore',
    apply: 'build',
    generateBundle(_options, bundle) {
      for (const [file, output] of Object.entries(bundle)) {
        const header = '/* biome-ignore-all lint format: generated by `bun run build:ui` */\n';
        if (file.endsWith('.js') && output.type === 'chunk' && !output.code.startsWith(header)) {
          output.code = header + output.code;
        } else if (file.endsWith('.css') && output.type === 'asset') {
          const css =
            typeof output.source === 'string'
              ? output.source
              : new TextDecoder().decode(output.source);
          if (!css.startsWith(header)) output.source = header + css;
        }
      }
    },
  };
}

/**
 * The host mounts plugin UI inside `<iframe sandbox="allow-scripts allow-forms">`
 * (no `allow-same-origin`), so the document has an opaque origin. Module scripts
 * are fetched in CORS mode and the gateway sends no `Access-Control-Allow-Origin`
 * for `/plugins/*`, so they never execute there (verified in headless Chrome).
 * A classic script at the end of `<body>` is not CORS-mode and sees `#root`
 * already parsed; that is the only form that boots under the sandbox.
 *
 * Guard: a classic script cannot contain ESM syntax. The three pages share one
 * entry/chunk, so this is safe today; the build fails loudly if that changes.
 */
function classicScriptForSandbox(): Plugin {
  return {
    name: 'vessel-classic-script',
    apply: 'build',
    enforce: 'post',
    transformIndexHtml(html) {
      const match = html.match(/<script type="module" crossorigin src="([^"]+)"><\/script>/);
      const tag = match?.[0];
      const src = match?.[1];
      if (tag === undefined || src === undefined) return html;
      // `crossorigin` makes the stylesheet a CORS request too; the sandboxed
      // opaque origin has no matching ACAO, so drop it (same-URL no-cors is
      // sufficient for a stylesheet).
      return html
        .replace(tag, '')
        .replace(/[ \t]+\n/g, '\n')
        .replace(/<link rel="stylesheet" crossorigin href=/g, '<link rel="stylesheet" href=')
        .replace('</body>', `<script src="${src}"></script></body>`);
    },
    generateBundle(_options, bundle) {
      for (const [file, output] of Object.entries(bundle)) {
        if (!file.endsWith('.js') || output.type !== 'chunk') continue;
        const esm =
          /(^|[\n;])\s*(?:import|export)\s*[{*(]/.test(output.code) ||
          /(^|[^\w$.])import\s*\(/.test(output.code) ||
          /\bimport\.meta\b/.test(output.code);
        if (esm) {
          this.error(
            `${file} contains ESM syntax; a sandboxed classic script cannot load it (use one chunk, no dynamic import).`,
          );
        }
      }
    },
  };
}

export default defineConfig({
  root,
  base: './',
  resolve: {
    // Same strategy as apps/web: consume the workspace package source
    // directly. `styles.css` must be matched before the package root.
    alias: [
      {
        find: '@vessel-agent/plugin-ui/styles.css',
        replacement: resolve(pluginUiSrc, 'styles.css'),
      },
      {
        find: /^@vessel-agent\/plugin-ui$/,
        replacement: resolve(pluginUiSrc, 'index.ts'),
      },
    ],
  },
  plugins: [react(), tailwindcss(), classicScriptForSandbox(), generatedBiomeIgnore()],
  build: {
    outDir: resolve(__dirname, 'web'),
    emptyOutDir: true,
    // The iframe is local; sourcemaps would only add committed noise.
    sourcemap: false,
    rollupOptions: {
      input: {
        usage: resolve(root, 'usage.html'),
        logs: resolve(root, 'logs.html'),
      },
    },
  },
});
