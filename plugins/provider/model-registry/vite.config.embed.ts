import { resolve } from 'node:path';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

/**
 * Model-registry plugin embed build (plugin-embed 契约 §10).
 *
 * Lib 模式 ESM 产物 `web/embed/index.mjs`（+ `index.css`）：React / SDK 全部
 * external 化，由宿主 import map 指向 vendor shim（与宿主 bundle 共用同一份
 * 实例）。iframe 产物仍由 vite.config.ts 的 classic-script 流程单独构建，
 * 两条产线共用同一份 web-src。
 */

/**
 * 契约 §9 要求 plugin.model-registry 层位于宿主 utilities **之前**。层序按首次
 * 声明排定，后加载的插件样式无法自行插队——真正的保证是宿主 index.css 预留了
 * `plugin` 槽位（legacy 与 utilities 之间），plugin.model-registry 嵌套其下。
 * 这里在产物最前再补一条完整层序声明作防御：在宿主控制台里它不引入任何新层
 * （properties/theme/base/legacy/utilities 均已声明，plugin.model-registry 落入
 * plugin 槽位），只兜底「插件 CSS 先于宿主样式加载」的异常时序。
 */
function pluginLayerOrder(): Plugin {
  const order = '@layer properties, theme, base, legacy, plugin.model-registry, utilities;\n';
  return {
    name: 'vessel-plugin-layer-order',
    apply: 'build',
    // post：lib + cssCodeSplit:false 的合并 CSS 由 vite:css 的 generateBundle
    // 才 emitFile，normal 钩子看不到它。两个 post 插件按数组顺序：先插层序
    // 声明，generatedBiomeIgnore 再把 biome 头插到最前。
    enforce: 'post',
    generateBundle(_options, bundle) {
      for (const [file, output] of Object.entries(bundle)) {
        if (!file.endsWith('.css') || output.type !== 'asset') continue;
        const css =
          typeof output.source === 'string'
            ? output.source
            : new TextDecoder().decode(output.source);
        if (!css.includes(order)) output.source = order + css;
      }
    },
  };
}

/**
 * 产物入库，必须带 biome-ignore-all 头（照 vite.config.ts 的
 * generatedBiomeIgnore；这里覆盖 .mjs chunk，并多抑制 assist 类——
 * organizeImports 会挑生成产物的 import 顺序，lint/format 头挡不住它）。
 */
function generatedBiomeIgnore(): Plugin {
  return {
    name: 'vessel-generated-biome-ignore',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      for (const [file, output] of Object.entries(bundle)) {
        const header =
          '/* biome-ignore-all lint format assist: generated by `bun run build:ui` */\n';
        if (
          (file.endsWith('.mjs') || file.endsWith('.js')) &&
          output.type === 'chunk' &&
          !output.code.startsWith(header)
        ) {
          output.code = header + output.code;
        } else if (file.endsWith('.css') && output.type === 'asset') {
          const css =
            typeof output.source === 'string'
              ? output.source
              : new TextDecoder().decode(output.source);
          if (!css.startsWith(header)) output.source = header + css;
        }
      }
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), pluginLayerOrder(), generatedBiomeIgnore()],
  build: {
    outDir: resolve(__dirname, 'web/embed'),
    emptyOutDir: true,
    cssCodeSplit: false,
    sourcemap: false,
    lib: {
      entry: resolve(__dirname, 'web-src/embed.tsx'),
      formats: ['es'],
      fileName: () => 'index.mjs',
      cssFileName: 'index',
    },
    rollupOptions: {
      // 宿主经 import map 提供这些模块（契约 §6）；打进产物就是第二份 React。
      external: [
        'react',
        'react-dom',
        'react-dom/client',
        'react/jsx-runtime',
        '@vessel-agent/plugin-sdk',
      ],
      output: {
        chunkFileNames: 'chunks/[name]-[hash].mjs',
        assetFileNames: '[name][extname]',
      },
    },
  },
});
