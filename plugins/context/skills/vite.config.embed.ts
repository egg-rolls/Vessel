import { resolve } from 'node:path';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

/**
 * Skills plugin embed build (plugin-embed contract §10).
 *
 * Lib-mode ESM payload `web/embed/index.mjs` (+ `index.css`): React / SDK are
 * externalized; the host import map points them at the vendor shims (same
 * instances as the host bundle). The iframe payload is built separately by
 * vite.config.ts's classic-script flow; both tiers share one web-src.
 */

/**
 * Contract §9 requires the plugin.skills layer before host utilities. Layer
 * order is fixed by first declaration; the real guarantee is the host
 * index.css reserving the `plugin` slot (between legacy and utilities), with
 * plugin.skills nested under it. This prepends a full layer-order declaration
 * as defense: inside the host console it introduces no new layers, only covers
 * the abnormal timing where plugin CSS loads before host styles.
 */
function pluginLayerOrder(): Plugin {
  const order = '@layer properties, theme, base, legacy, plugin.skills, utilities;\n';
  return {
    name: 'vessel-plugin-layer-order',
    apply: 'build',
    // post: lib + cssCodeSplit:false merged CSS is emitted by vite:css's
    // generateBundle; normal hooks never see it. The two post plugins run in
    // array order: layer order first, then the biome header at the very top.
    enforce: 'post',
    generateBundle(_options, bundle) {
      for (const [file, output] of Object.entries(bundle)) {
        if (!file.endsWith('.css') || output.type !== 'asset') continue;
        const css =
          typeof output.source === 'string'
            ? output.source
            : new TextDecoder().decode(output.source);
        if (!css.includes(order)) output.source = order + css;
      }
    },
  };
}

/**
 * Committed artifacts must carry the biome-ignore-all header (same as
 * vite.config.ts's generatedBiomeIgnore; this also covers .mjs chunks and
 * suppresses assist rules — organizeImports would otherwise pick at the
 * generated import order).
 */
function generatedBiomeIgnore(): Plugin {
  return {
    name: 'vessel-generated-biome-ignore',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      for (const [file, output] of Object.entries(bundle)) {
        const header =
          '/* biome-ignore-all lint format assist: generated by `bun run build:ui` */\n';
        if (
          (file.endsWith('.mjs') || file.endsWith('.js')) &&
          output.type === 'chunk' &&
          !output.code.startsWith(header)
        ) {
          output.code = header + output.code;
        } else if (file.endsWith('.css') && output.type === 'asset') {
          const css =
            typeof output.source === 'string'
              ? output.source
              : new TextDecoder().decode(output.source);
          if (!css.startsWith(header)) output.source = header + css;
        }
      }
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), pluginLayerOrder(), generatedBiomeIgnore()],
  build: {
    outDir: resolve(__dirname, 'web/embed'),
    emptyOutDir: true,
    cssCodeSplit: false,
    sourcemap: false,
    lib: {
      entry: resolve(__dirname, 'web-src/embed.tsx'),
      formats: ['es'],
      fileName: () => 'index.mjs',
      cssFileName: 'index',
    },
    rollupOptions: {
      // The host provides these modules via import map (contract §6);
      // bundling them would create a second React instance.
      external: [
        'react',
        'react-dom',
        'react-dom/client',
        'react/jsx-runtime',
        '@vessel-agent/plugin-sdk',
      ],
      output: {
        chunkFileNames: 'chunks/[name]-[hash].mjs',
        assetFileNames: '[name][extname]',
      },
    },
  },
});
