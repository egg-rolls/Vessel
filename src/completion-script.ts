/**
 * Shell 补全脚本生成器（0.18）。
 *
 * 只读 `completion-spec.ts` 的静态数据，输出可直接 source / 加载的脚本。
 * 不启动 runtime、不联网、不读取配置；动态值（session / tenant / agent id）
 * 不写进脚本，交给各 shell 的默认文件补全。
 *
 * @module vessel/completion-script
 */

// 生成器的字符串字面量里会有 shell 的 `${var}`（例如 `${COMP_WORDS[1]}`），
// 它们是要写进脚本的文本，不是模板占位；本文件的模板插值都写成 `${expr}`。
// biome-ignore-all lint/suspicious/noTemplateCurlyInString: literal shell placeholders

import {
  COMPLETION_COMMANDS,
  type CompletionShell,
  DYNAMIC_VALUE_FLAGS,
  GLOBAL_FLAGS,
  OPTIONAL_VALUE_FLAGS,
  topLevelWords,
} from './completion-spec';

const DYNAMIC = new Set(DYNAMIC_VALUE_FLAGS);
const OPTIONAL = new Set(OPTIONAL_VALUE_FLAGS);

/** 每个一次性命令 / 子命令都接受 `--help`；全局 flags 只在顶层有效 */
const HELP_FLAGS: readonly string[] = ['--help', '-h'];

/** bash 生成脚本里的当前词（避免在模板里写转义插值） */
const BASH_CUR = '"${cur}"';

/** POSIX shell（bash / zsh / fish）单引号转义 */
function sh(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/** PowerShell 单引号转义 */
function ps(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function unique(values: readonly string[]): string[] {
  return [...new Set(values)];
}

interface StaticValue {
  /** 命令上下文：`gateway start` / `update` */
  context: string;
  flag: string;
  values: readonly string[];
}

function staticValues(): StaticValue[] {
  const entries: StaticValue[] = [];
  for (const command of COMPLETION_COMMANDS) {
    for (const [flag, values] of Object.entries(command.flagValues ?? {})) {
      entries.push({ context: command.token, flag, values });
    }
    for (const sub of command.subcommands ?? []) {
      for (const [flag, values] of Object.entries(sub.flagValues ?? {})) {
        entries.push({ context: `${command.token} ${sub.name}`, flag, values });
      }
    }
  }
  return entries;
}

/** 命令自有 flags（不含全局 flags） */
function ownFlags(token: string, subcommand?: string): readonly string[] {
  const command = COMPLETION_COMMANDS.find((entry) => entry.token === token);
  if (command === undefined) return [];
  const sub = command.subcommands?.find((entry) => entry.name === subcommand);
  return [...(command.flags ?? []), ...(sub?.flags ?? [])];
}

// ── bash ─────────────────────────────────────────

const BASH_DYNAMIC_CASE = unique(DYNAMIC_VALUE_FLAGS)
  .map((flag) => sh(flag))
  .join('|');

function bashCommandBlock(token: string): string[] {
  const command = COMPLETION_COMMANDS.find((entry) => entry.token === token);
  if (command === undefined) return [];
  const commandFlags = unique([...HELP_FLAGS, ...(command.flags ?? [])]);
  const subcommands = command.subcommands ?? [];
  const lines: string[] = [`    ${sh(token)})`];

  if (subcommands.length === 0) {
    lines.push(`      COMPREPLY=( $(compgen -W ${sh(commandFlags.join(' '))} -- ${BASH_CUR}) )`);
    lines.push('      return 0');
    lines.push('      ;;');
    return lines;
  }

  const subWords = unique([...subcommands.map((sub) => sub.name), ...commandFlags]);
  lines.push('      if [[ -n "${sub}" ]]; then');
  lines.push('        case "${sub}" in');
  for (const sub of subcommands) {
    const flags = unique([...HELP_FLAGS, ...(sub.flags ?? [])]);
    lines.push(
      `          ${sh(sub.name)}) COMPREPLY=( $(compgen -W ${sh(flags.join(' '))} -- ${BASH_CUR}) ) ;;`,
    );
  }
  lines.push(
    `          *) COMPREPLY=( $(compgen -W ${sh(subWords.join(' '))} -- ${BASH_CUR}) ) ;;`,
  );
  lines.push('        esac');
  lines.push('      elif [[ "${cur}" == -* ]]; then');
  lines.push(`        COMPREPLY=( $(compgen -W ${sh(commandFlags.join(' '))} -- ${BASH_CUR}) )`);
  lines.push('      else');
  lines.push(`        COMPREPLY=( $(compgen -W ${sh(subWords.join(' '))} -- ${BASH_CUR}) )`);
  lines.push('      fi');
  lines.push('      return 0');
  lines.push('      ;;');
  return lines;
}

function renderBash(): string {
  const lines: string[] = [
    '# vessel shell completion for bash',
    '# Generated by `vessel completion bash`.',
    '# Install:',
    '#   vessel completion bash > ~/.local/share/bash-completion/completions/vessel',
    '# or for the current session:',
    '#   source <(vessel completion bash)',
    '',
    '_vessel() {',
    '  local cur prev cmd sub w i skip',
    '  COMPREPLY=()',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  prev="${COMP_WORDS[COMP_CWORD - 1]}"',
    '',
    '  # The first non-flag word is the command; the next one is its subcommand.',
    '  cmd=""',
    '  sub=""',
    '  skip=0',
    '  for ((i = 1; i < COMP_CWORD; i++)); do',
    '    w="${COMP_WORDS[i]}"',
    '    if [[ "${skip}" -eq 1 ]]; then',
    '      skip=0',
    '      continue',
    '    fi',
    '    case "${w}" in',
    `      ${BASH_DYNAMIC_CASE}) skip=1; continue ;;`,
    '      -*) continue ;;',
    '    esac',
    '    if [[ -z "${cmd}" ]]; then',
    '      cmd="${w}"',
    '    elif [[ -z "${sub}" ]]; then',
    '      sub="${w}"',
    '    fi',
    '  done',
    '',
    '  # Static flag values.',
    '  case "${cmd}${sub:+ ${sub}}|${prev}" in',
  ];
  for (const entry of staticValues()) {
    lines.push(
      `    ${sh(`${entry.context}|${entry.flag}`)}) ` +
        `COMPREPLY=( $(compgen -W ${sh(entry.values.join(' '))} -- ${BASH_CUR}) ); return 0 ;;`,
    );
  }
  lines.push(
    '  esac',
    '',
    '  # Dynamic values (paths / ids / numbers): fall back to -o default file completion.',
    '  case "${prev}" in',
    `    ${BASH_DYNAMIC_CASE}) return 0 ;;`,
    '  esac',
    '',
    '  if [[ -z "${cmd}" ]]; then',
    `    COMPREPLY=( $(compgen -W ${sh(topLevelWords().join(' '))} -- ${BASH_CUR}) )`,
    '    return 0',
    '  fi',
    '',
    '  case "${cmd}" in',
  );
  for (const command of COMPLETION_COMMANDS) {
    if (command.token.startsWith('-')) continue;
    lines.push(...bashCommandBlock(command.token));
  }
  lines.push(
    '  esac',
    '',
    `  COMPREPLY=( $(compgen -W ${sh(GLOBAL_FLAGS.join(' '))} -- ${BASH_CUR}) )`,
    '}',
    '',
    'complete -o default -F _vessel vessel',
    '',
  );
  return lines.join('\n');
}

// ── zsh ─────────────────────────────────────────

function zshFlagSpec(flag: string, values?: readonly string[]): string {
  const description = 'Vessel option';
  if (values !== undefined) {
    return `'${flag}[${description}]:value:(${values.join(' ')})'`;
  }
  if (OPTIONAL.has(flag)) return `'${flag}[${description}]::value:'`;
  if (DYNAMIC.has(flag)) return `'${flag}[${description}]:value:'`;
  return `'${flag}[${description}]'`;
}

function zshFlagSpecs(
  flags: readonly string[],
  values?: Readonly<Record<string, readonly string[]>>,
) {
  return unique(flags).map((flag) => zshFlagSpec(flag, values?.[flag]));
}

/** 多行 `_arguments` 调用 */
function zshArgumentsCall(indent: string, specs: readonly string[]): string[] {
  if (specs.length === 0) return [`${indent}_arguments`];
  const lines: string[] = [`${indent}_arguments \\`];
  specs.forEach((spec, index) => {
    const suffix = index === specs.length - 1 ? '' : ' \\';
    lines.push(`${indent}  ${spec}${suffix}`);
  });
  return lines;
}

function renderZsh(): string {
  const lines: string[] = [
    '#compdef vessel',
    '# vessel shell completion for zsh',
    '# Generated by `vessel completion zsh`.',
    '# Install (fpath):',
    '#   mkdir -p ~/.zsh/completions',
    '#   vessel completion zsh > ~/.zsh/completions/_vessel',
    '#   fpath=(~/.zsh/completions $fpath)',
    '#   autoload -Uz compinit && compinit',
    '# or for the current session:',
    '#   source <(vessel completion zsh)',
    '',
    '_vessel() {',
    '  local -a commands',
    '  commands=(',
  ];
  for (const command of COMPLETION_COMMANDS) {
    if (command.token.startsWith('-')) continue;
    lines.push(`    ${sh(`${command.token}:Vessel command`)}`);
  }
  lines.push('  )');
  const topSpecs = [...zshFlagSpecs(GLOBAL_FLAGS), "'1:command:->vessel_command'"];
  lines.push(...zshArgumentsCall('  ', [...topSpecs, "'*::argument:->vessel_args'"]));
  lines.push(
    '  case "${state}" in',
    '    vessel_command)',
    "      _describe -t commands 'vessel command' commands",
    '      ;;',
    '    vessel_args)',
    '      case "${words[1]}" in',
  );

  for (const command of COMPLETION_COMMANDS) {
    if (command.token.startsWith('-')) continue;
    const commandFlags = unique([...HELP_FLAGS, ...(command.flags ?? [])]);
    const subcommands = command.subcommands ?? [];
    lines.push(`        ${sh(command.token)})`);
    if (subcommands.length === 0) {
      lines.push(...zshArgumentsCall('          ', zshFlagSpecs(commandFlags, command.flagValues)));
      lines.push('          ;;');
      continue;
    }
    const fixedValues = subcommands.every(
      (sub) => (sub.flags?.length ?? 0) === 0 && sub.flagValues === undefined,
    );
    if (fixedValues) {
      const values = subcommands.map((sub) => sub.name).join(' ');
      lines.push(
        ...zshArgumentsCall('          ', [
          ...zshFlagSpecs(commandFlags, command.flagValues),
          `'1:value:(${values})'`,
        ]),
      );
      lines.push('          ;;');
      continue;
    }
    const stateName = `vessel_${command.token.replaceAll('-', '_')}_args`;
    const subSpecs = [
      ...zshFlagSpecs(commandFlags, command.flagValues),
      `'1:subcommand:(${subcommands.map((sub) => sub.name).join(' ')})'`,
      `'*::argument:->${stateName}'`,
    ];
    lines.push(...zshArgumentsCall('          ', subSpecs));
    lines.push('          case "${state}" in');
    lines.push(`            ${stateName})`);
    lines.push('              case "${words[1]}" in');
    for (const sub of subcommands) {
      const subFlags = unique([...HELP_FLAGS, ...(sub.flags ?? [])]);
      lines.push(`                ${sh(sub.name)})`);
      lines.push(...zshArgumentsCall('                  ', zshFlagSpecs(subFlags, sub.flagValues)));
      lines.push('                  ;;');
    }
    lines.push('                *)');
    lines.push(...zshArgumentsCall('                  ', zshFlagSpecs(commandFlags)));
    lines.push('                  ;;');
    lines.push('              esac');
    lines.push('              ;;');
    lines.push('          esac');
    lines.push('          ;;');
  }

  lines.push(
    '        *)',
    '          ;;',
    '      esac',
    '      ;;',
    '  esac',
    '}',
    '',
    'if [[ "${funcstack[1]}" == "_vessel" ]]; then',
    '  _vessel "$@"',
    'elif (( $+functions[compdef] )); then',
    '  compdef _vessel vessel',
    'fi',
    '',
  );
  return lines.join('\n');
}

// ── fish ─────────────────────────────────────────

function fishFlagArgs(flag: string): string {
  if (flag.startsWith('--')) return `-l ${flag.slice(2)}`;
  return `-s ${flag.slice(1)}`;
}

function fishFlagLines(
  flags: readonly string[],
  values: Readonly<Record<string, readonly string[]>> | undefined,
  condition: string | null,
): string[] {
  const lines: string[] = [];
  const valueFlags = new Set(Object.keys(values ?? {}));
  const conditionArg = condition === null ? '' : ` -n ${sh(condition)}`;
  for (const flag of unique(flags)) {
    if (valueFlags.has(flag)) continue;
    const requiresArg = DYNAMIC.has(flag) ? ' -r' : '';
    lines.push(
      `complete -c vessel -f ${fishFlagArgs(flag)}${requiresArg} -d 'Vessel option'${conditionArg}`,
    );
  }
  for (const [flag, candidates] of Object.entries(values ?? {})) {
    lines.push(
      `complete -c vessel -f ${fishFlagArgs(flag)} -r -a ${sh(candidates.join(' '))} ` +
        `-d 'Vessel option'${conditionArg}`,
    );
  }
  return lines;
}

function renderFish(): string {
  const lines: string[] = [
    '# vessel shell completion for fish',
    '# Generated by `vessel completion fish`.',
    '# Install:',
    '#   vessel completion fish > ~/.config/fish/completions/vessel.fish',
    '',
  ];

  for (const command of COMPLETION_COMMANDS) {
    if (command.token.startsWith('-')) continue;
    lines.push(
      `complete -c vessel -f -n '__fish_use_subcommand' -a ${sh(command.token)} ` +
        `-d 'Vessel command'`,
    );
  }
  lines.push(...fishFlagLines(HELP_FLAGS, undefined, null));
  const topGlobalFlags = GLOBAL_FLAGS.filter((flag) => !HELP_FLAGS.includes(flag));
  lines.push(...fishFlagLines(topGlobalFlags, undefined, '__fish_use_subcommand'));
  for (const command of COMPLETION_COMMANDS) {
    if (command.token.startsWith('-')) continue;
    const seen = `__fish_seen_subcommand_from ${command.token}`;
    const subNames = (command.subcommands ?? []).map((sub) => sub.name);
    const atCommand =
      subNames.length === 0
        ? seen
        : `${seen}; and not __fish_seen_subcommand_from ${subNames.join(' ')}`;
    const commandFlags = ownFlags(command.token);
    lines.push(...fishFlagLines(commandFlags, command.flagValues, atCommand));
    for (const sub of command.subcommands ?? []) {
      lines.push(
        `complete -c vessel -f -n ${sh(atCommand)} -a ${sh(sub.name)} -d 'Vessel subcommand'`,
      );
      const subCondition = `${seen}; and __fish_seen_subcommand_from ${sub.name}`;
      lines.push(...fishFlagLines(sub.flags ?? [], sub.flagValues, subCondition));
    }
  }
  lines.push('');
  return lines.join('\n');
}

// ── powershell ──────────────────────────────────

/** PowerShell 数组字面量 */
function psArray(values: readonly string[]): string {
  return `@(${values.map((value) => ps(value)).join(', ')})`;
}

/** PowerShell 哈希表字面量；空表返回 `@{}` */
function psMap(entries: ReadonlyArray<readonly [string, string]>): string[] {
  if (entries.length === 0) return ['@{}'];
  const lines = ['@{'];
  for (const [key, value] of entries) {
    lines.push(`        ${ps(key)} = ${value}`);
  }
  lines.push('    }');
  return lines;
}

function renderPowerShell(): string {
  const commandTokens = COMPLETION_COMMANDS.filter((command) => !command.token.startsWith('-')).map(
    (command) => command.token,
  );

  const subEntries: Array<readonly [string, string]> = [];
  const commandFlagEntries: Array<readonly [string, string]> = [];
  const subFlagEntries: Array<readonly [string, string]> = [];
  for (const command of COMPLETION_COMMANDS) {
    if (command.token.startsWith('-')) continue;
    if ((command.subcommands?.length ?? 0) > 0) {
      subEntries.push([command.token, psArray((command.subcommands ?? []).map((sub) => sub.name))]);
    }
    if ((command.flags?.length ?? 0) > 0) {
      commandFlagEntries.push([command.token, psArray(command.flags ?? [])]);
    }
    for (const sub of command.subcommands ?? []) {
      if ((sub.flags?.length ?? 0) > 0) {
        subFlagEntries.push([`${command.token} ${sub.name}`, psArray(sub.flags ?? [])]);
      }
    }
  }

  const lines: string[] = [
    '# vessel shell completion for PowerShell',
    '# Generated by `vessel completion powershell`.',
    '# Install (current session):',
    '#   vessel completion powershell | Out-String | Invoke-Expression',
    '# Persist: add the same line to $PROFILE',
    '',
    'Register-ArgumentCompleter -Native -CommandName vessel -ScriptBlock {',
    '    param($wordToComplete, $commandAst, $cursorPosition)',
    '',
    `    $commands = ${psArray(commandTokens)}`,
    `    $globalFlags = ${psArray(GLOBAL_FLAGS)}`,
    `    $valueFlags = ${psArray(DYNAMIC_VALUE_FLAGS)}`,
    `    $helpFlags = ${psArray(HELP_FLAGS)}`,
    '',
    `    $subcommands = ${psMap(subEntries).join('\n')}`,
    `    $commandFlags = ${psMap(commandFlagEntries).join('\n')}`,
    `    $subFlags = ${psMap(subFlagEntries).join('\n')}`,
    `    $flagValues = ${psMap(
      staticValues().map(
        (entry) => [`${entry.context}|${entry.flag}`, psArray(entry.values)] as const,
      ),
    ).join('\n')}`,
    '',
    '    $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.Extent.Text })',
    '    if ($words.Count -gt 0 -and $wordToComplete -ne "" -and $words[-1] -eq $wordToComplete) {',
    '        if ($words.Count -gt 1) {',
    '            $words = @($words[0..($words.Count - 2)])',
    '        } else {',
    '            $words = @()',
    '        }',
    '    }',
    '',
    '    $prev = ""',
    '    if ($words.Count -gt 0) { $prev = $words[$words.Count - 1] }',
    '',
    '    $cmd = ""',
    '    $sub = ""',
    '    $skip = $false',
    '    foreach ($word in $words) {',
    '        if ($skip) { $skip = $false; continue }',
    '        if ($valueFlags -contains $word) { $skip = $true; continue }',
    '        if ($word.StartsWith("-")) { continue }',
    '        if ($cmd -eq "") { $cmd = $word } elseif ($sub -eq "") { $sub = $word }',
    '    }',
    '',
    '    $context = $cmd',
    '    if ($sub -ne "") { $context = "$cmd $sub" }',
    '',
    '    $candidates = @()',
    '    $valueKey = "$context|$prev"',
    '    if ($flagValues.ContainsKey($valueKey)) {',
    '        $candidates = $flagValues[$valueKey]',
    '    } elseif ($valueFlags -contains $prev) {',
    '        return',
    '    } elseif ($cmd -eq "" -and -not $wordToComplete.StartsWith("-")) {',
    '        $candidates = $commands + $globalFlags',
    '    } elseif ($sub -eq "" -and -not $wordToComplete.StartsWith("-") -and $subcommands.ContainsKey($cmd)) {',
    '        $candidates = @($subcommands[$cmd])',
    '        if ($commandFlags.ContainsKey($cmd)) { $candidates += $commandFlags[$cmd] }',
    '        $candidates += $helpFlags',
    '    } else {',
    '        if ($commandFlags.ContainsKey($cmd)) { $candidates += $commandFlags[$cmd] }',
    '        if ($subFlags.ContainsKey("$cmd $sub")) { $candidates += $subFlags["$cmd $sub"] }',
    '        $candidates += $helpFlags',
    '    }',
    '',
    '    $candidates | Where-Object { $_ -ne $null } | Sort-Object -Unique | Where-Object {',
    '        $_.StartsWith($wordToComplete, [System.StringComparison]::OrdinalIgnoreCase)',
    '    } | ForEach-Object {',
    '        [System.Management.Automation.CompletionResult]::new($_, $_, "ParameterValue", $_)',
    '    }',
    '}',
    '',
  ];
  return lines.join('\n');
}

const RENDERERS: Record<CompletionShell, () => string> = {
  bash: renderBash,
  zsh: renderZsh,
  fish: renderFish,
  powershell: renderPowerShell,
};

/** 生成指定 shell 的补全脚本（以换行结尾） */
export function renderCompletionScript(shell: CompletionShell): string {
  return RENDERERS[shell]();
}
